# Writes the design tokens in design/tokens.json as C# (Windows) and Kotlin (Android).
# Usage: tools/Generate-DesignTokens.ps1 [-AndroidRoot <path to UsageNotch-Android>]
param([string]$AndroidRoot = (Join-Path $PSScriptRoot '..\Release\AndroidWorkspace\UsageNotch-Android'))
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$tokens = Get-Content -Raw -Encoding UTF8 (Join-Path $root 'design\tokens.json') | ConvertFrom-Json
$inv = [Globalization.CultureInfo]::InvariantCulture

function Argb([string]$hex) {
    $h = $hex.TrimStart('#')
    if ($h.Length -eq 6) { $h = 'FF' + $h }
    if ($h.Length -ne 8) { throw "Bad colour $hex" }
    return '0x' + $h.ToUpperInvariant()
}
function Pascal([string]$name) { (($name -split '[-_]') | ForEach-Object { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }) -join '' }
function Num($v) { ([double]$v).ToString('0.0###', $inv) }

$cs = [Text.StringBuilder]::new()
[void]$cs.AppendLine('// <auto-generated> by tools/Generate-DesignTokens.ps1 from design/tokens.json. Edit the JSON, not this file. </auto-generated>')
[void]$cs.AppendLine('namespace UsageNotch.Services;')
[void]$cs.AppendLine('')
[void]$cs.AppendLine('public static class DesignTokens')
[void]$cs.AppendLine('{')
[void]$cs.AppendLine('    public static readonly (double Stop, uint Argb)[] UsageRamp = [' + (($tokens.usageRamp | ForEach-Object { "($(Num $_.stop), $(Argb $_.color))" }) -join ', ') + '];')
foreach ($p in $tokens.status.PSObject.Properties) { [void]$cs.AppendLine("    public const uint $(Pascal $p.Name) = $(Argb $p.Value);") }
[void]$cs.AppendLine('    public static readonly IReadOnlyDictionary<string, uint> Brand = new Dictionary<string, uint> { ' + (($tokens.brand.PSObject.Properties | ForEach-Object { "[`"$($_.Name)`"] = $(Argb $_.Value)" }) -join ', ') + ' };')
[void]$cs.AppendLine('    public static readonly uint[] AccentChoices = [' + (($tokens.accentChoices | ForEach-Object { Argb $_ }) -join ', ') + '];')
[void]$cs.AppendLine('    public static readonly uint[] Ambient = [' + (($tokens.ambient | ForEach-Object { Argb $_ }) -join ', ') + '];')
foreach ($theme in 'dark', 'light') {
    [void]$cs.AppendLine("    public static class $(Pascal $theme)")
    [void]$cs.AppendLine('    {')
    foreach ($p in $tokens.$theme.PSObject.Properties) {
        if ($p.Value -is [string]) { [void]$cs.AppendLine("        public const uint $(Pascal $p.Name) = $(Argb $p.Value);") }
        else { [void]$cs.AppendLine("        public const double $(Pascal $p.Name) = $(Num $p.Value);") }
    }
    [void]$cs.AppendLine('    }')
}
[void]$cs.AppendLine('    public static class TypeScale { ' + (($tokens.typeScale.PSObject.Properties | ForEach-Object { "public const double $(Pascal $_.Name) = $(Num $_.Value);" }) -join ' ') + ' }')
[void]$cs.AppendLine('    public static class Spacing { ' + (($tokens.spacing.PSObject.Properties | ForEach-Object { "public const double $(Pascal $_.Name) = $(Num $_.Value);" }) -join ' ') + ' }')
[void]$cs.AppendLine('    public static class Radius { ' + (($tokens.radius.PSObject.Properties | ForEach-Object { "public const double $(Pascal $_.Name) = $(Num $_.Value);" }) -join ' ') + ' }')
[void]$cs.AppendLine('    public static class Motion')
[void]$cs.AppendLine('    {')
foreach ($p in $tokens.motion.PSObject.Properties | Where-Object Name -ne 'springs') { [void]$cs.AppendLine("        public const int $(Pascal $p.Name) = $($p.Value);") }
foreach ($p in $tokens.motion.springs.PSObject.Properties) { [void]$cs.AppendLine("        public static readonly (double Damping, double Stiffness) $(Pascal $p.Name) = ($(Num $p.Value.damping), $(Num $p.Value.stiffness));") }
[void]$cs.AppendLine('    }')
[void]$cs.AppendLine("    public const int WarnPercent = $($tokens.thresholds.warn), CriticalPercent = $($tokens.thresholds.critical);")
[void]$cs.AppendLine("    public const double GlowFraction = $(Num $tokens.thresholds.glow);")
[void]$cs.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $root 'Services\DesignTokens.g.cs'), $cs.ToString(), [Text.UTF8Encoding]::new($false))

$kt = [Text.StringBuilder]::new()
[void]$kt.AppendLine('// Generated by tools/Generate-DesignTokens.ps1 in UsageNotch-Windows from design/tokens.json. Edit the JSON, not this file.')
[void]$kt.AppendLine('package io.github.arnavdugad.usagenotch')
[void]$kt.AppendLine('')
[void]$kt.AppendLine('@Suppress("MemberVisibilityCanBePrivate", "unused")')
[void]$kt.AppendLine('object DesignTokens {')
[void]$kt.AppendLine('    val usageRamp: List<Pair<Double, Int>> = listOf(' + (($tokens.usageRamp | ForEach-Object { "$(Num $_.stop) to $(Argb $_.color).toInt()" }) -join ', ') + ')')
foreach ($p in $tokens.status.PSObject.Properties) { [void]$kt.AppendLine("    const val $($p.Name.ToUpperInvariant()) = $(Argb $p.Value).toInt()") }
[void]$kt.AppendLine('    val brand: Map<String, Int> = mapOf(' + (($tokens.brand.PSObject.Properties | ForEach-Object { "`"$($_.Name)`" to $(Argb $_.Value).toInt()" }) -join ', ') + ')')
[void]$kt.AppendLine('    val accentChoices: List<Int> = listOf(' + (($tokens.accentChoices | ForEach-Object { "$(Argb $_).toInt()" }) -join ', ') + ')')
[void]$kt.AppendLine('    val ambient: List<Int> = listOf(' + (($tokens.ambient | ForEach-Object { "$(Argb $_).toInt()" }) -join ', ') + ')')
foreach ($theme in 'dark', 'light') {
    [void]$kt.AppendLine("    object $(Pascal $theme) {")
    foreach ($p in $tokens.$theme.PSObject.Properties) {
        if ($p.Value -is [string]) { [void]$kt.AppendLine("        const val $($p.Name) = $(Argb $p.Value).toInt()") }
        else { [void]$kt.AppendLine("        const val $($p.Name) = $(Num $p.Value)f") }
    }
    [void]$kt.AppendLine('    }')
}
[void]$kt.AppendLine('    object TypeScale { ' + (($tokens.typeScale.PSObject.Properties | ForEach-Object { "const val $($_.Name) = $(Num $_.Value)f" }) -join '; ') + ' }')
[void]$kt.AppendLine('    object Spacing { ' + (($tokens.spacing.PSObject.Properties | ForEach-Object { "const val $($_.Name) = $(Num $_.Value)f" }) -join '; ') + ' }')
[void]$kt.AppendLine('    object Radius { ' + (($tokens.radius.PSObject.Properties | ForEach-Object { "const val $($_.Name) = $(Num $_.Value)f" }) -join '; ') + ' }')
[void]$kt.AppendLine('    object Motion {')
foreach ($p in $tokens.motion.PSObject.Properties | Where-Object Name -ne 'springs') { [void]$kt.AppendLine("        const val $($p.Name) = $($p.Value)") }
foreach ($p in $tokens.motion.springs.PSObject.Properties) { [void]$kt.AppendLine("        val $($p.Name) = $(Num $p.Value.damping)f to $(Num $p.Value.stiffness)f") }
[void]$kt.AppendLine('    }')
[void]$kt.AppendLine("    const val WARN_PERCENT = $($tokens.thresholds.warn)")
[void]$kt.AppendLine("    const val CRITICAL_PERCENT = $($tokens.thresholds.critical)")
[void]$kt.AppendLine("    const val GLOW_FRACTION = $(Num $tokens.thresholds.glow)f")
[void]$kt.AppendLine('}')
$ktPath = Join-Path $AndroidRoot 'app\src\main\java\io\github\arnavdugad\usagenotch\DesignTokens.kt'
if (Test-Path (Split-Path $ktPath -Parent)) {
    [IO.File]::WriteAllText($ktPath, $kt.ToString(), [Text.UTF8Encoding]::new($false))
    Copy-Item (Join-Path $root 'design\tokens.json') (Join-Path $AndroidRoot 'design-tokens.json') -Force
    Write-Host "Wrote $ktPath"
} else { Write-Warning "Android repository not found at $AndroidRoot; wrote C# only." }
Write-Host 'Wrote Services\DesignTokens.g.cs'
